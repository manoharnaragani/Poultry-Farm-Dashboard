export const getLanguage = () => language;
export function setLanguage(value) {
  language = value === 'te' ? 'te' : 'en';
  try { localStorage.setItem('nestledger.language', language); } catch {}
  document.documentElement.lang = language;
}
export function translate(text) {
  if (language !== 'te') return text;
  const trimmed = text.trim();
  if (telugu[trimmed]) return text.replace(trimmed, telugu[trimmed]);
  const patterns = [
    [/^Shed ([123])$/, (_, n) => `షెడ్ ${n}`],
    [/^(\d+) records?$/, (_, n) => `${n} రికార్డులు`],
    [/^Showing (.+) of (\d+)$/, (_, range, total) => `${total}లో ${range} చూపిస్తున్నాం`],
    [/^Search (.+)…$/, (_, name) => `${telugu[name[0].toUpperCase() + name.slice(1)] || name} శోధించండి…`],
    [/^(.+) - All dates$/, (_, name) => `${telugu[name] || name} - అన్ని తేదీలు`],
    [/^(\d+) active workers$/, (_, n) => `${n} క్రియాశీల కార్మికులు`],
    [/^Shed ([123]) daily collection$/, (_, n) => `షెడ్ ${n} రోజువారీ సేకరణ`],
    [/^Production, feed usage, expenses, and workers for Shed ([123])\.$/, (_, n) => `షెడ్ ${n} ఉత్పత్తి, దాణా వినియోగం, ఖర్చులు మరియు కార్మికులు.`],
  ];
  for (const [pattern, replacement] of patterns) if (pattern.test(trimmed)) return text.replace(trimmed, trimmed.replace(pattern, replacement));
  return text;
}

// Translate UI text only. User-entered records, input values and option values stay intact.
export function translateUI(root) {
  if (language !== 'te') return;
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  const nodes = [];
  while (walker.nextNode()) nodes.push(walker.currentNode);
  for (const node of nodes) {
    const parent = node.parentElement;
    if (!parent || parent.closest('script,style,textarea,[data-no-translate],.table-name,.table-sub,.profile-name,.brand-name,.stat-value,.summary-value')) continue;
    if (parent.closest('td') && !parent.closest('.badge,.row-actions,.table-empty')) continue;
    const value = translate(node.nodeValue);
    if (value !== node.nodeValue) node.nodeValue = value;
  }
  for (const element of root.querySelectorAll('[placeholder],[aria-label],[title]')) {
    for (const attr of ['placeholder', 'aria-label', 'title']) {
      const value = element.getAttribute(attr);
      if (value) {
        const translated = translate(value);
        if (translated !== value) element.setAttribute(attr, translated);
      }
    }
  }
}

export function watchTranslations() {
  document.documentElement.lang = language;
  const observer = new MutationObserver(() => translateUI(document.body));
  observer.observe(document.body, { childList: true, subtree: true, characterData: true });
}
